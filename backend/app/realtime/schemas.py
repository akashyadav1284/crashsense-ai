"""
Pydantic Schemas and Data Contracts for Phase 7: Real-Time Monitoring & Prediction Tracking.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Dict, Any, List, Optional, Tuple
from pydantic import BaseModel, Field


class RoundLifecycleStatus(str, Enum):
    WAITING = "WAITING"
    STARTED = "STARTED"
    ACTIVE = "ACTIVE"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    UNKNOWN = "UNKNOWN"


class ConnectionHealthStatus(str, Enum):
    HEALTHY = "HEALTHY"
    DEGRADED = "DEGRADED"
    DISCONNECTED = "DISCONNECTED"
    ERROR = "ERROR"
    NOT_CONFIGURED = "NOT_CONFIGURED"


class EstimateLifecycleStatus(str, Enum):
    GENERATED = "GENERATED"
    PENDING_OUTCOME = "PENDING_OUTCOME"
    SCORED = "SCORED"
    UNMATCHED = "UNMATCHED"
    INVALIDATED = "INVALIDATED"


class RealtimeRawEvent(BaseModel):
    event_id: str
    event_type: str  # round_started, round_updated, round_completed, heartbeat, data_quality_warning
    platform_id: str
    provider_id: str
    game_id: str
    room_id: str
    round_id: Optional[str] = None
    multiplier: Optional[float] = None
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    source_identity: str
    source_timestamp: Optional[datetime] = None
    payload: Dict[str, Any] = Field(default_factory=dict)
    schema_version: str = "1.0.0"


class LiveRoundRecord(BaseModel):
    round_id: str
    platform_id: str
    provider_id: str
    game_id: str
    room_id: str
    status: RoundLifecycleStatus = RoundLifecycleStatus.WAITING
    start_timestamp: Optional[datetime] = None
    completion_timestamp: Optional[datetime] = None
    actual_multiplier: Optional[float] = None
    source_identity: str
    verification_status: str = "UNVERIFIED"
    event_received_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    event_processed_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    data_freshness_ms: float = 0.0


class ResearchEstimateRecord(BaseModel):
    estimate_id: str
    platform_id: str
    provider_id: str
    game_id: str
    room_id: str
    round_id: Optional[str] = None
    model_id: str
    model_version: str
    experiment_id: Optional[str] = None
    dataset_snapshot_id: Optional[str] = None
    source_provenance: str
    estimate_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    feature_window_end_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    model_validation_status: str  # VALIDATED, REJECTED, STANDBY
    calibration_status: str  # CALIBRATED, UNCALIBRATED
    target_threshold: float = 2.0
    predicted_probability: float  # P(multiplier >= target_threshold)
    baseline_probability: float  # Theoretical CSPRNG P
    decision_signal: str  # PASS, NO_SIGNAL
    confidence_interval: Tuple[float, float] = (0.0, 1.0)
    status: EstimateLifecycleStatus = EstimateLifecycleStatus.PENDING_OUTCOME
    actual_multiplier: Optional[float] = None
    outcome_timestamp: Optional[datetime] = None
    is_correct: Optional[bool] = None
    brier_error: Optional[float] = None
    scientific_disclaimer: str = (
        "RESEARCH MONITORING ONLY. Experimental ML research estimate. "
        "Crash multipliers are generated by cryptographic PRNG sequences. "
        "Not a guaranteed prediction. Do not use for automated betting."
    )


class ScoredOutcomeRecord(BaseModel):
    estimate_id: str
    round_id: str
    platform_id: str
    provider_id: str
    game_id: str
    room_id: str
    model_id: str
    predicted_probability: float
    target_threshold: float
    actual_multiplier: float
    outcome_timestamp: datetime
    scored_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    actual_label: int  # 1 if actual_multiplier >= target_threshold else 0
    predicted_label: int  # 1 if predicted_probability >= 0.5 else 0
    is_correct: bool
    brier_score: float
    log_loss: float


class ConnectorHealthStatus(BaseModel):
    connector_id: str
    platform_id: str
    provider_id: str
    name: str
    status: ConnectionHealthStatus = ConnectionHealthStatus.NOT_CONFIGURED
    is_authorized: bool = False
    last_heartbeat: Optional[datetime] = None
    last_event_received: Optional[datetime] = None
    uptime_seconds: float = 0.0
    reconnection_count: int = 0
    latency_ms: float = 0.0
    recent_errors: List[str] = Field(default_factory=list)


class OperationalMetrics(BaseModel):
    active_connectors: int = 0
    healthy_connectors: int = 0
    disconnected_connectors: int = 0
    events_received: int = 0
    events_processed: int = 0
    events_rejected: int = 0
    duplicate_events: int = 0
    out_of_order_events: int = 0
    failed_processing_jobs: int = 0
    websocket_client_count: int = 0
    inference_execution_count: int = 0
    pending_outcome_count: int = 0
    scored_outcome_count: int = 0
    average_processing_latency_ms: float = 0.0
    last_event_timestamp: Optional[datetime] = None


class EstimateEvaluationSummary(BaseModel):
    total_estimates: int = 0
    scored_estimates: int = 0
    pending_estimates: int = 0
    unmatched_estimates: int = 0
    invalidated_estimates: int = 0
    accuracy: float = 0.0
    brier_score: float = 0.25
    log_loss: float = 0.69315
    baseline_brier_score: float = 0.25
    baseline_log_loss: float = 0.69315
    has_validated_edge: bool = False
    calibration_error: float = 0.0
    prediction_coverage: float = 0.0
    confusion_matrix: List[List[int]] = Field(default_factory=lambda: [[0, 0], [0, 0]])

